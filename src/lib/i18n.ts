export function translator(lang: Lang) {
  const table = STRINGS[lang] as Record<string, unknown>;
  const t = (key: string, ...args: (number | string)[]): string => {
    const value = table[key];
    if (typeof value === "function") return value(...args);
    return typeof value === "string" ? value : "";
  };
  return { lang, t };
}

export type Translator = ReturnType<typeof translator>;

export const I18n = createContext<Translator>(translator("ka"));
export const useI18n = () => useContext(I18n);

export function storedLanguage(): Lang {
  try {
    return localStorage.getItem("lang") === "en" ? "en" : "ka";
  } catch {
    return "ka";
  }
}

export function storeLanguage(lang: Lang) {
  try {
    localStorage.setItem("lang", lang);
  } catch {
    /* private mode */
  }
}
